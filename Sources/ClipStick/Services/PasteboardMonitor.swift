import AppKit

/// Polls `NSPasteboard.general.changeCount` and turns changes into `CaptureDraft`s.
@MainActor
final class PasteboardMonitor {
    var isPaused = false
    var onCapture: ((CaptureDraft) -> Void)?

    private var lastChangeCount: Int
    private var timer: Timer?

    /// Password managers mark secrets with these types; never record them.
    private static let ignoredTypes: Set<NSPasteboard.PasteboardType> = [
        .init("org.nspasteboard.ConcealedType"),
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
        .init("com.agilebits.onepassword"),
    ]

    init() { lastChangeCount = NSPasteboard.general.changeCount }

    func start() {
        guard timer == nil else { return }
        schedule()
        let ws = NSWorkspace.shared.notificationCenter
        for name in [NSWorkspace.willSleepNotification, NSWorkspace.screensDidSleepNotification] {
            ws.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.suspend() }
            }
        }
        for name in [NSWorkspace.didWakeNotification, NSWorkspace.screensDidWakeNotification] {
            ws.addObserver(forName: name, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.schedule(); self?.poll() }
            }
        }
        NotificationCenter.default.addObserver(forName: .NSProcessInfoPowerStateDidChange, object: nil, queue: .main) { [weak self] _ in
            MainActor.assumeIsolated { self?.schedule() }
        }
    }

    func stop() { suspend() }

    private func suspend() { timer?.invalidate(); timer = nil }

    /// Battery friendliness: a changeCount check is nearly free, but wakeups aren't. Use a slow interval with
    /// generous tolerance so the OS can coalesce our timer with others, back off in Low Power Mode, and
    /// stop entirely while the display or machine sleeps.
    private func schedule() {
        timer?.invalidate()
        let interval: TimeInterval = ProcessInfo.processInfo.isLowPowerModeEnabled ? 1.0 : 0.5
        let t = Timer(timeInterval: interval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        t.tolerance = interval * 0.5
        RunLoop.main.add(t, forMode: .common)
        timer = t
    }

    /// Call after ClipStick itself writes to the pasteboard so the write isn't re-captured.
    func syncChangeCount() { lastChangeCount = NSPasteboard.general.changeCount }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        guard !isPaused else { return }
        if let types = pb.types, !Self.ignoredTypes.isDisjoint(with: types) { return }
        guard let payload = Self.readPayload(from: pb) else { return }

        let front = NSWorkspace.shared.frontmostApplication
        let isSelf = front?.processIdentifier == ProcessInfo.processInfo.processIdentifier
        onCapture?(CaptureDraft(
            payload: payload,
            sourceApp: isSelf ? "ClipStick" : front?.localizedName,
            sourceBundleID: isSelf ? nil : front?.bundleIdentifier
        ))
    }

    /// Priority: files > image > text.
    private static func readPayload(from pb: NSPasteboard) -> CaptureDraft.Payload? {
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            return .files(urls)
        }
        if let png = pb.data(forType: .png) { return .imageData(png) }
        if let tiff = pb.data(forType: .tiff) { return .imageData(tiff) }
        if let s = pb.string(forType: .string), !s.isEmpty { return .text(s) }
        return nil
    }
}
